import './style.css';
import type { Network } from 'zcash-zip321';
import { announce, byId, h } from './dom.ts';
import { EXAMPLES } from './examples.ts';
import { decodeHash, encodeHash } from './hash.ts';
import { inspect, type InspectOptions } from './inspect.ts';
import { cameraAvailable, cameraErrorMessage, decodeImageFile, preloadQrLibraries, qrSvg, startScanner, type Scanner } from './qr.ts';
import { render } from './render.ts';

const input = byId<HTMLTextAreaElement>('uri');
const examples = byId<HTMLSelectElement>('examples');
const network = byId<HTMLSelectElement>('network');
const validate = byId<HTMLInputElement>('validate');
const summary = byId('summary');
const results = byId('results');
const scanButton = byId<HTMLButtonElement>('scan');
const uploadButton = byId<HTMLButtonElement>('upload');
const fileInput = byId<HTMLInputElement>('file');
const scanner = byId('scanner');
const video = byId<HTMLVideoElement>('video');
const qrStatus = byId('qr-status');

// Examples menu, grouped into valid and invalid requests.
for (const valid of [true, false]) {
  examples.append(
    h(
      'optgroup',
      { label: valid ? 'Valid requests' : 'Invalid requests' },
      EXAMPLES.filter((e) => e.valid === valid).map((e) => h('option', { value: e.id }, e.title)),
    ),
  );
}

function options(): InspectOptions {
  const out: InspectOptions = {};
  if (network.value) out.network = network.value as Network;
  if (!validate.checked) out.validateAddresses = false;
  return out;
}

let drawToken = 0;
function drawQr(container: HTMLElement, uri: string) {
  const token = ++drawToken;
  container.classList.add('loading');
  qrSvg(uri)
    .then((svg) => {
      if (token !== drawToken) return;
      // The SVG is generated by the qrcode library from the module matrix; it holds no input text.
      container.innerHTML = svg;
      container.classList.remove('loading');
    })
    .catch(() => {
      if (token !== drawToken) return;
      container.classList.remove('loading');
      container.replaceChildren(h('p', { class: 'muted small' }, 'This URI is too long for a QR code.'));
    });
}

function update() {
  const start = performance.now();
  const result = inspect(input.value, options());
  const elapsedMs = performance.now() - start;
  render(result, summary, results, {
    elapsedMs,
    drawQr,
    useCanonical(uri) {
      input.value = uri;
      update();
      input.focus();
      announce('Replaced the input with the canonical form');
    },
  });
  writeHash();
}

let timer: ReturnType<typeof setTimeout> | undefined;
function scheduleUpdate() {
  clearTimeout(timer);
  timer = setTimeout(update, 120);
}

// URL hash: #uri=…&network=…&validate=0
function writeHash() {
  const state: Parameters<typeof encodeHash>[0] = { uri: input.value.trim() };
  if (network.value) state.network = network.value as Network;
  if (!validate.checked) state.validateAddresses = false;
  const hash = encodeHash(state);
  if (hash === location.hash || (!hash && !location.hash)) return;
  history.replaceState(null, '', hash || `${location.pathname}${location.search}`);
}

function readHash() {
  const state = decodeHash(location.hash);
  input.value = state.uri ?? '';
  network.value = state.network ?? '';
  validate.checked = state.validateAddresses !== false;
}

input.addEventListener('input', () => {
  examples.value = '';
  scheduleUpdate();
});
network.addEventListener('change', update);
validate.addEventListener('change', update);

examples.addEventListener('change', () => {
  const example = EXAMPLES.find((e) => e.id === examples.value);
  if (!example) return;
  input.value = example.uri;
  network.value = example.network ?? '';
  validate.checked = example.validateAddresses !== false;
  update();
  announce(`Loaded example: ${example.title}`);
});

byId('clear').addEventListener('click', () => {
  input.value = '';
  examples.value = '';
  update();
  input.focus();
});

window.addEventListener('hashchange', () => {
  const state = decodeHash(location.hash);
  if ((state.uri ?? '') === input.value.trim()) return;
  readHash();
  update();
});

// QR input
function useScanned(text: string, source: string) {
  input.value = text;
  examples.value = '';
  update();
  qrStatus.textContent = text.toLowerCase().startsWith('zcash:')
    ? `Read a payment request from the ${source}.`
    : `Read a QR code from the ${source}, but it does not hold a zcash: URI.`;
}

uploadButton.addEventListener('click', () => fileInput.click());
fileInput.addEventListener('change', async () => {
  const file = fileInput.files?.[0];
  fileInput.value = '';
  if (!file) return;
  qrStatus.textContent = 'Reading the image…';
  try {
    const text = await decodeImageFile(file);
    if (text === undefined) qrStatus.textContent = 'No QR code was found in that image. Try a sharper or closer picture.';
    else useScanned(text, 'image');
  } catch {
    qrStatus.textContent = 'That file could not be read as an image.';
  }
});

let active: Scanner | undefined;
function stopScanning() {
  active?.stop();
  active = undefined;
  scanner.hidden = true;
  scanButton.setAttribute('aria-expanded', 'false');
}

if (cameraAvailable()) {
  scanButton.hidden = false;
  scanButton.setAttribute('aria-controls', 'scanner');
  scanButton.setAttribute('aria-expanded', 'false');
  scanButton.addEventListener('click', async () => {
    if (active) {
      stopScanning();
      scanButton.focus();
      return;
    }
    scanner.hidden = false;
    scanButton.setAttribute('aria-expanded', 'true');
    qrStatus.textContent = 'Starting the camera…';
    try {
      active = await startScanner(video, (text) => {
        stopScanning();
        useScanned(text, 'camera');
        input.focus();
      });
      qrStatus.textContent = 'Camera on. Point it at a QR code.';
    } catch (err) {
      stopScanning();
      qrStatus.textContent = cameraErrorMessage(err);
    }
  });
  byId('stop-scan').addEventListener('click', () => {
    stopScanning();
    qrStatus.textContent = 'Camera stopped.';
    scanButton.focus();
  });
  document.addEventListener('keydown', (event) => {
    if (event.key === 'Escape' && active) {
      stopScanning();
      qrStatus.textContent = 'Camera stopped.';
      scanButton.focus();
    }
  });
}

readHash();
update();

// Fetch the lazily loaded QR libraries once the page is idle, so they are cached for offline use.
const idle = (globalThis as { requestIdleCallback?: (cb: () => void) => void }).requestIdleCallback ?? ((cb: () => void) => setTimeout(cb, 1500));
idle(preloadQrLibraries);
